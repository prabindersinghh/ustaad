"use client";

import { Section, Panel, Caption, Reveal, Pending } from "./primitives";
import { Results as R, useDemoJSON } from "@/lib/demo";

function pct(x: number | null) {
  return x == null ? "—" : `${Math.round(x * 100)}%`;
}

export default function Results() {
  const { data, loaded } = useDemoJSON<R>("results.json");

  const cards = data
    ? [
        { v: pct(data.metrics.recall_wrong), label: "Wrong steps caught (recall)" },
        { v: pct(data.metrics.false_alarm_rate), label: "False alarms on correct steps" },
        { v: pct(data.metrics.precision), label: "Precision of FAIL verdicts" },
        { v: data.median_latency_ms == null ? "—" : `${data.median_latency_ms} ms`, label: "Median latency per step" },
      ]
    : [];

  return (
    <Section
      id="results"
      num="§6"
      eyebrow="Evaluation"
      title="Measured, not claimed."
      sub="Every number below is read live from results.json, produced by eval.py against a labelled set. If the file is absent, the figure says pending — nothing is hardcoded."
    >
      {loaded && !data ? (
        <Panel className="mt-8">
          <div className="flex flex-col items-start gap-3">
            <div className="flex flex-wrap gap-2"><span className="chip">synthetic data</span><span className="chip">browser fallback</span></div>
            <p className="text-[14px] text-ash">The page is running in simulation mode; no evaluation numbers are invented before the pipeline publishes results.</p>
            <div className="grid w-full grid-cols-2 gap-3 md:grid-cols-4">{["recall","false alarms","precision","latency"].map((x)=><div key={x} className="rounded-lg border border-line bg-bone p-3"><div className="text-[28px] text-ash">—</div><div className="text-[12px] text-ash">{x}</div></div>)}</div>
            <p className="text-[12px] text-ash">Run <span className="font-mono">bash pipeline/run_all.sh</span> on Linux to replace placeholders with measured synthetic results.</p>
          </div>
        </Panel>
      ) : (
        <>
          {data?.synthetic && (
            <div className="mt-6 inline-flex items-center gap-2 rounded-full border border-yellow/60 bg-yellow/15 px-3 py-1 font-mono text-[12px] text-[#875A00]">
              <span className="h-1.5 w-1.5 rounded-full bg-yellow" />
              synthetic data — generated by make_synthetic.py
            </div>
          )}

          <div className="mt-6 grid grid-cols-2 gap-4 md:grid-cols-4">
            {cards.map((c, i) => (
              <Reveal key={c.label} delay={i * 0.05}>
                <Panel className="h-full">
                  <div className="text-[34px] font-semibold tracking-[-0.02em] text-ink">
                    {c.v || <span className="text-ash">—</span>}
                  </div>
                  <div className="mt-1 text-[13px] text-ash">{c.label}</div>
                </Panel>
              </Reveal>
            ))}
          </div>

          {data && (
            <div className="mt-5 grid gap-4 md:grid-cols-[1fr_1.3fr]">
              <Reveal>
                <Panel className="h-full">
                  <div className="caption mb-3"><b>Confusion counts</b></div>
                  <div className="grid grid-cols-2 gap-2 font-mono text-[12.5px]">
                    {Object.entries(data.counts).map(([k, v]) => (
                      <div key={k} className="flex items-center justify-between rounded-md border border-line bg-bone px-3 py-2">
                        <span className="text-ash uppercase">{k}</span>
                        <span className="text-ink">{v}</span>
                      </div>
                    ))}
                  </div>
                  <div className="caption mt-3">
                    {data.n_labeled} labelled stable moments · uncertain rate {pct(data.metrics.uncertain_rate)}
                  </div>
                </Panel>
              </Reveal>

              <Reveal delay={0.05}>
                <Panel className="h-full">
                  <div className="caption mb-3"><b>Failure cases</b></div>
                  {data.failure_cases.length === 0 ? (
                    <p className="text-[13px] text-ash">No misses or false alarms on this run.</p>
                  ) : (
                    <ul className="space-y-2">
                      {data.failure_cases.map((f, i) => (
                        <li key={i} className="rounded-lg border border-line bg-bone px-3 py-2 font-mono text-[12px] text-ash">
                          t={f.t}s · step {f.step} · <span className="text-fail">{f.why}</span>
                          {f.score != null && <> · ssim={f.score}</>}
                        </li>
                      ))}
                    </ul>
                  )}
                  <p className="mt-3 text-[12.5px] leading-relaxed text-ash">
                    Known hard cases — strong reflections, hands occluding the region, large camera
                    movement after capture — fall into the uncertain band and escalate to a human.
                  </p>
                </Panel>
              </Reveal>
            </div>
          )}
          <Caption fig="Fig. 4">
            Ground truth from <span className="font-mono">data/labels.csv</span>; the synthetic set is
            labelled automatically. Metrics recompute whenever <span className="font-mono">run_all.sh</span> re-runs.
          </Caption>
        </>
      )}
    </Section>
  );
}
